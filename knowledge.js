document.addEventListener('DOMContentLoaded', () => {
    const knowledgeBtn = document.getElementById('knowledgeBtn');
    const knowledgeModal = document.getElementById('knowledgeModal');
    const closeKnowledgeBtn = document.getElementById('closeKnowledgeBtn');
    const knowledgeBody = document.getElementById('knowledgeBody');

    if (knowledgeBtn && knowledgeModal && knowledgeBody) {
        knowledgeBody.innerHTML = marked.parse(KNOWLEDGE_MARKDOWN);

        knowledgeBtn.addEventListener('click', () => {
            knowledgeModal.classList.add('active');
        });

        closeKnowledgeBtn.addEventListener('click', () => {
            knowledgeModal.classList.remove('active');
        });
        
        knowledgeModal.addEventListener('click', (e) => {
            if (e.target === knowledgeModal) {
                knowledgeModal.classList.remove('active');
            }
        });
    }
});
